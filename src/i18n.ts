const dicts = { pl, en } as { pl: Record<I18nKey, string>; en: Record<I18nKey, string> };

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  let s = dicts[settings.lang][key] ?? dicts.pl[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  return s;
}

/** Podmienia teksty w statycznym HTML-u (atrybuty data-i18n*). */
export function applyI18n(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n as I18nKey);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle as I18nKey);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-placeholder]').forEach((el) => {
    (el as HTMLInputElement).placeholder = t(el.dataset.i18nPlaceholder as I18nKey);
  });
  document.documentElement.lang = settings.lang;
  const out = document.getElementById('output');
  if (out) out.dataset.empty = t('output.empty');
}
